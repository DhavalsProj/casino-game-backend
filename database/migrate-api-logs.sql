-- Add persistent, redacted request/response logging to an existing database.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS api_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id varchar(64) NOT NULL,
  method varchar(10) NOT NULL,
  path text NOT NULL,
  status_code integer NOT NULL,
  duration_ms integer NOT NULL,
  user_id integer,
  user_type varchar(20),
  ip_address varchar(45),
  user_agent varchar(500),
  request_headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_query jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_body jsonb,
  response_body jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_api_logs_created_at
  ON api_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_api_logs_user_created_at
  ON api_logs (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_api_logs_status_created_at
  ON api_logs (status_code, created_at DESC);
