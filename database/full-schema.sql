-- Complete schema for a NEW, EMPTY PostgreSQL database.
-- Run this once when setting up another local environment.
-- Do not use this file to upgrade an existing database; use the migrations.

BEGIN;

-- Accounts and authentication
CREATE TABLE IF NOT EXISTS "Users" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  mobile varchar(15) NOT NULL UNIQUE,
  type varchar(20) NOT NULL CHECK (type IN ('superadmin', 'agent', 'user')),
  agent_id integer,
  unique_id varchar(10) UNIQUE,
  password_hash varchar(255) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_agent_id_users_id
    FOREIGN KEY (agent_id) REFERENCES "Users" (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_users_agent_id ON "Users" (agent_id);

CREATE TABLE IF NOT EXISTS "SystemCredentials" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CredentialName" varchar(50) NOT NULL UNIQUE,
  "PasswordHash" varchar(255) NOT NULL,
  "ProfileName" varchar(100),
  "ProfileMobile" varchar(15),
  "IsActive" boolean NOT NULL DEFAULT true,
  "CreatedAt" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "UpdatedAt" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "LoginAudit" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES "Users" (id) ON DELETE SET NULL,
  unique_id varchar(10),
  login_type varchar(20) NOT NULL CHECK (login_type IN ('NORMAL', 'MASTER')),
  login_status varchar(20) NOT NULL CHECK (login_status IN ('SUCCESS', 'FAILED')),
  ip_address varchar(45),
  user_agent varchar(500),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_login_audit_user_id ON "LoginAudit" (user_id);
CREATE INDEX IF NOT EXISTS ix_login_audit_created_at ON "LoginAudit" (created_at);

-- Redacted API request/response audit log. No password/token headers are stored.
CREATE TABLE IF NOT EXISTS api_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id varchar(64) NOT NULL,
  method varchar(10) NOT NULL,
  path text NOT NULL,
  status_code integer NOT NULL,
  duration_ms integer NOT NULL,
  user_id integer,
  user_type varchar(20),
  ip_address varchar(45),
  user_agent varchar(500),
  request_headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_query jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_body jsonb,
  response_body jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_api_logs_created_at
  ON api_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_api_logs_user_created_at
  ON api_logs (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_api_logs_status_created_at
  ON api_logs (status_code, created_at DESC);

-- Wallets, requests, actions, and immutable balance ledger
DO $$ BEGIN
  CREATE TYPE wallet_requests_type_enum AS ENUM ('ADD_POINTS', 'WITHDRAW');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE wallet_requests_status_enum AS ENUM ('PENDING', 'ACCEPTED', 'REJECTED');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE wallet_request_actions_action_enum AS ENUM ('CREATED', 'ACCEPTED', 'REJECTED');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE transactions_type_enum AS ENUM ('CREDIT', 'DEBIT');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE transactions_source_enum AS ENUM
    ('ADMIN_ADD', 'WITHDRAW', 'GAME_WIN', 'GAME_ENTRY', 'BONUS', 'REFUND', 'OTHER');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS wallets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES "Users" (id) ON DELETE CASCADE,
  balance numeric(15,2) NOT NULL DEFAULT 0,
  temporary_winning_balance numeric(15,2) NOT NULL DEFAULT 0 CHECK (temporary_winning_balance >= 0),
  -- These actor IDs intentionally have no FK: Super Admin actor ID is 0.
  created_by integer NOT NULL,
  updated_by integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wallet_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES "Users" (id) ON DELETE CASCADE,
  wallet_id integer NOT NULL REFERENCES wallets (id) ON DELETE CASCADE,
  type wallet_requests_type_enum NOT NULL,
  amount numeric(15,2) NOT NULL CHECK (amount > 0),
  status wallet_requests_status_enum NOT NULL DEFAULT 'PENDING',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_wallet_requests_user_status_created
  ON wallet_requests (user_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS wallet_request_actions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id integer NOT NULL REFERENCES wallet_requests (id) ON DELETE CASCADE,
  performed_by integer REFERENCES "Users" (id) ON DELETE SET NULL,
  action wallet_request_actions_action_enum NOT NULL,
  balance_before numeric(15,2),
  balance_after numeric(15,2),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wallet_id integer NOT NULL REFERENCES wallets (id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES "Users" (id) ON DELETE CASCADE,
  request_id integer REFERENCES wallet_requests (id) ON DELETE SET NULL,
  type transactions_type_enum NOT NULL,
  source transactions_source_enum NOT NULL,
  balance_bucket varchar(30) NOT NULL DEFAULT 'MAIN' CHECK (balance_bucket IN ('MAIN', 'TEMPORARY_WINNING')),
  amount numeric(15,2) NOT NULL CHECK (amount > 0),
  balance_before numeric(15,2) NOT NULL,
  balance_after numeric(15,2) NOT NULL,
  description text,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_transactions_user_created
  ON transactions (user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_transactions_request_id
  ON transactions (request_id);

-- Fun Target game configuration and rounds
CREATE SEQUENCE IF NOT EXISTS fun_target_round_number_seq;

CREATE TABLE IF NOT EXISTS fun_target_config (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  game_name varchar NOT NULL DEFAULT 'Fun Target',
  min_bet numeric(15,2) NOT NULL DEFAULT 1.00 CHECK (min_bet > 0),
  max_bet numeric(15,2) NOT NULL DEFAULT 5000.00
    CHECK (max_bet >= min_bet AND max_bet <= 5000),
  denominations jsonb NOT NULL DEFAULT '[1,5,10,50,100,500,1000,5000]'::jsonb,
  denomination_restrictions boolean NOT NULL DEFAULT true,
  result_mode varchar NOT NULL DEFAULT 'MANUAL'
    CHECK (result_mode IN ('MANUAL', 'RANDOM')),
  joker_enabled boolean NOT NULL DEFAULT false,
  joker_multiplier integer NOT NULL DEFAULT 2 CHECK (joker_multiplier > 0),
  joker_frequency integer NOT NULL DEFAULT 5 CHECK (joker_frequency > 0),
  admin_share_percent numeric(5,2) NOT NULL DEFAULT 60
    CHECK (admin_share_percent BETWEEN 0 AND 100),
  winning_allocation_percent numeric(5,2) NOT NULL DEFAULT 40
    CHECK (winning_allocation_percent BETWEEN 0 AND 100),
  active boolean NOT NULL DEFAULT true,
  created_by integer,
  updated_by integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (admin_share_percent + winning_allocation_percent = 100)
);

CREATE TABLE IF NOT EXISTS fun_target_rounds (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_number integer NOT NULL UNIQUE DEFAULT nextval('fun_target_round_number_seq'),
  status varchar NOT NULL DEFAULT 'UPCOMING'
    CHECK (status IN ('UPCOMING', 'OPEN', 'CLOSED', 'COMPLETED')),
  scheduled_at timestamptz NOT NULL UNIQUE,
  opened_at timestamptz,
  closed_at timestamptz,
  result_mode varchar NOT NULL CHECK (result_mode IN ('MANUAL', 'RANDOM')),
  joker_enabled boolean NOT NULL DEFAULT false,
  joker_multiplier integer NOT NULL DEFAULT 1 CHECK (joker_multiplier > 0),
  winning_number integer CHECK (winning_number BETWEEN 1 AND 9),
  result_generated_by integer,
  result_generated_at timestamptz,
  finalized_by integer,
  finalized_at timestamptz,
  created_by integer,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fun_target_bets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id integer NOT NULL REFERENCES fun_target_rounds (id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES "Users" (id) ON DELETE CASCADE,
  number integer NOT NULL CHECK (number BETWEEN 1 AND 9),
  amount numeric(15,2) NOT NULL CHECK (amount > 0),
  idempotency_key varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_fun_target_bets_round_number
  ON fun_target_bets (round_id, number);

CREATE TABLE IF NOT EXISTS fun_target_joker_schedules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id integer NOT NULL UNIQUE REFERENCES fun_target_rounds (id) ON DELETE CASCADE,
  multiplier integer NOT NULL CHECK (multiplier > 0),
  active boolean NOT NULL DEFAULT true,
  created_by integer,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fun_target_result_audit (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id integer NOT NULL REFERENCES fun_target_rounds (id) ON DELETE CASCADE,
  actor_id integer NOT NULL,
  action varchar(30) NOT NULL,
  winning_number integer CHECK (winning_number BETWEEN 1 AND 9),
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMIT;

