DO $$ BEGIN
    CREATE TYPE wallet_requests_type_enum AS ENUM ('ADD_POINTS', 'WITHDRAW');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$
DECLARE
    has_add_points BOOLEAN;
    has_credit BOOLEAN;
    has_withdraw BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1
        FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'wallet_requests_type_enum'
          AND e.enumlabel = 'ADD_POINTS'
    ) INTO has_add_points;
    SELECT EXISTS (
        SELECT 1
        FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'wallet_requests_type_enum'
          AND e.enumlabel = 'CREDIT'
    ) INTO has_credit;

    IF has_credit AND NOT has_add_points THEN
        ALTER TYPE wallet_requests_type_enum
            RENAME VALUE 'CREDIT' TO 'ADD_POINTS';
        has_add_points := TRUE;
    ELSIF NOT has_add_points THEN
        ALTER TYPE wallet_requests_type_enum
            ADD VALUE 'ADD_POINTS';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'wallet_requests_type_enum'
          AND e.enumlabel = 'WITHDRAW'
    ) INTO has_withdraw;
    IF NOT has_withdraw THEN
        ALTER TYPE wallet_requests_type_enum
            ADD VALUE 'WITHDRAW';
    END IF;
END $$;

