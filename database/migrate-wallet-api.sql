CREATE TABLE IF NOT EXISTS wallet_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES "Users" (id) ON DELETE CASCADE,
    wallet_id INTEGER NOT NULL REFERENCES wallets (id) ON DELETE CASCADE,
    type wallet_requests_type_enum NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    status wallet_requests_status_enum NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

UPDATE wallet_requests
SET type = 'ADD_POINTS'
WHERE type::TEXT = 'CREDIT';

CREATE TABLE IF NOT EXISTS wallet_request_actions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES wallet_requests (id) ON DELETE CASCADE,
    performed_by INTEGER REFERENCES "Users" (id) ON DELETE SET NULL,
    action wallet_request_actions_action_enum NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id INTEGER NOT NULL REFERENCES wallets (id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES "Users" (id) ON DELETE CASCADE,
    request_id INTEGER REFERENCES wallet_requests (id) ON DELETE SET NULL,
    type transactions_type_enum NOT NULL,
    source transactions_source_enum NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    balance_before NUMERIC(15,2) NOT NULL,
    balance_after NUMERIC(15,2) NOT NULL,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

