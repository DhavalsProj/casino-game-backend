CREATE TABLE IF NOT EXISTS "Users" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    mobile VARCHAR(15) NOT NULL UNIQUE,
    type VARCHAR(20) NOT NULL CHECK (type IN ('superadmin', 'agent', 'user')),
    agent_id VARCHAR(10),
    unique_id VARCHAR(10) NOT NULL UNIQUE,
    password VARCHAR(255),
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_users_agent_id
    ON "Users" (agent_id);


CREATE TABLE IF NOT EXISTS "SystemCredentials" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CredentialName" VARCHAR(50) NOT NULL UNIQUE,
    "PasswordHash" VARCHAR(255) NOT NULL,
    "IsActive" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS "LoginAudit" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES "Users" (id),
    unique_id VARCHAR(10),
    login_type VARCHAR(20) NOT NULL CHECK (login_type IN ('NORMAL', 'MASTER')),
    login_status VARCHAR(20) NOT NULL CHECK (login_status IN ('SUCCESS', 'FAILED')),
    ip_address VARCHAR(45),
    user_agent VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_login_audit_user_id
    ON "LoginAudit" (user_id);

CREATE INDEX IF NOT EXISTS ix_login_audit_created_at
    ON "LoginAudit" (created_at);


CREATE TABLE IF NOT EXISTS wallets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES "Users" (id),
    balance NUMERIC(15,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
